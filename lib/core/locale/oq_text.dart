import 'package:flutter/material.dart';

import 'app_language.dart';

export 'app_language.dart';

class LanguageButton extends StatelessWidget {
  const LanguageButton({super.key, this.light = false});

  final bool light;

  @override
  Widget build(BuildContext context) {
    final color = light ? Colors.white : const Color(0xFF20201E);
    return PopupMenuButton<String>(
      tooltip: tr('Language'),
      initialValue: AppLanguage.instance.code,
      onSelected: AppLanguage.instance.setCode,
      itemBuilder: (context) => const [
        PopupMenuItem(value: 'en', child: Text('English')),
        PopupMenuItem(value: 'hi', child: Text('हिन्दी')),
        PopupMenuItem(value: 'ar', child: Text('العربية')),
      ],
      child: Padding(
        padding: const EdgeInsets.symmetric(horizontal: 10),
        child: Center(
          child: Text(
            AppLanguage.instance.shortLabel,
            style: TextStyle(color: color, fontWeight: FontWeight.w700, fontSize: 16),
          ),
        ),
      ),
    );
  }
}

Widget oqDirection(Widget child) {
  return Directionality(
    textDirection: AppLanguage.instance.direction,
    child: child,
  );
}

String tr(String english) {
  final code = AppLanguage.instance.code;
  if (code == 'en' || english.isEmpty) return english;
  final table = code == 'hi' ? _hindi : _arabic;
  return table[english] ?? table[english.trim()] ?? english;
}

